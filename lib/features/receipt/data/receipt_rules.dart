// ────────────────────────────── 金额 ──────────────────────────────

/// 一条金额锚点。
///
/// [actualPay] = 该锚点指向"用户真正付出的钱"（区别于原价 / 优惠）。
/// [tag] 只用于诊断与"识别依据"文案。
typedef AmountAnchor = ({String tag, bool actualPay, RegExp pattern});

/// 金额锚点表（**顺序即优先级**，理由见 `auto_book_rules.dart` 的同款注释）。
///
/// 数字部分统一允许千分位（`1,234.00`）与最多两位小数；全部走 `yuanToCents` 字符串转分。
final List<AmountAnchor> kAmountAnchors = <AmountAnchor>[
  // ① 明确写"实付 / 支付金额"的
  (
    tag: '实付',
    actualPay: true,
    pattern: RegExp(
      r'(?:实付|实际支付|实际付款|支付金额|付款金额|扣款金额|支出金额|消费金额|交易金额|支付总额)'
      r'\s*[:：]?\s*[¥￥]?\s*(-?\d[\d,]*(?:\.\d{1,2})?)',
    ),
  ),
  // ② 退款金额（方向不同，但同样是"真金额"）
  (
    tag: '退款金额',
    actualPay: true,
    pattern: RegExp(r'退款金额\s*[:：]?\s*[¥￥]?\s*(-?\d[\d,]*(?:\.\d{1,2})?)'),
  ),
  // ③ 金额在动作词之前（支付宝真实文案：「你有一笔0.01元的支出」）
  (
    tag: '动作前',
    actualPay: true,
    pattern: RegExp(
      r'(-?\d[\d,]*(?:\.\d{1,2})?)\s*元\s*的?\s*(?:支出|消费|收入|付款|支付|收款)',
    ),
  ),
  // ④ 订单合计（电商页面常见；可能是含运费的总额，故不算 actualPay）
  (
    tag: '合计',
    actualPay: false,
    pattern: RegExp(
      r'(?:合计|总计|应付|实收款|订单金额|商品总额)\s*[:：]?\s*[¥￥]?\s*(-?\d[\d,]*(?:\.\d{1,2})?)',
    ),
  ),
  // ⑤ 货币符号
  (
    tag: '¥',
    actualPay: true,
    pattern: RegExp(r'[¥￥]\s*(-?\d[\d,]*(?:\.\d{1,2})?)'),
  ),
  // ⑥ 「N 元」
  (
    tag: '元',
    actualPay: true,
    pattern: RegExp(r'(-?\d[\d,]*(?:\.\d{1,2})?)\s*元'),
  ),
  // ⑦ 独占一行的裸金额（截图里金额常常就是这样一行：`12.00` / `-3.00` / `+5.00`）
  //    ⚠️ 必须带**捕获组**：解析层统一取 group(1)，漏了组会抛 RangeError
  (
    tag: '独立行',
    actualPay: true,
    pattern: RegExp(r'^\s*([+-]?\d{1,7}\.\d{2})\s*$'),
  ),
];

